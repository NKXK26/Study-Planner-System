const assert=require('node:assert/strict');
(async()=>{
 const {plannerIntake,samePlannerIntake,compatibleSecondMajorChoices}=await import('../src/app/libs/plannerIntake.mjs');
 const {doubleMajorPathway,rankedSecondMajors}=await import('../src/app/libs/doubleMajorPathway.mjs');
 const {parseTranscript,assessDpaDoubleMajor}=await import('../src/app/libs/doubleMajorChecker.mjs');
 for(const name of ['24-Sep-CSDS','2024 September CSAI','24 Sept CSDSr2','24_sep_CSDS','24–Sep–CSAI']){
  assert.equal(plannerIntake(name).key,'2024:sep',name);
 }
 assert.equal(plannerIntake('23-Feb-CSAI').label,'23-Feb');
 assert.equal(plannerIntake('22-S1-CSDS').key,'2022:s1');
 assert.equal(samePlannerIntake('22-S1-CSDS','22-S2-CSAI'),false);
 assert.equal(samePlannerIntake('23-Feb-CSAI','23-S1-CSDS'),false,'Do not infer a month-to-semester mapping');
 assert.equal(samePlannerIntake('24-Sep-CSDS','23-Sep-CSAI'),false);
 assert.equal(samePlannerIntake('24-Sep-CSDS','24-Feb-CSAI'),false);
 assert.equal(samePlannerIntake('AI','DS'),false,'Two unknown intakes are not a match');
 assert.equal(plannerIntake('24-Septics-CSAI'),null,'A partial month inside another word is not an intake');
 let id=0;
 const u=(code,type='Major')=>({ID:++id,UnitCode:code,Name:code,CreditPoints:12.5,Availability:'Published',unitType:{Name:type},UnitTermOffered:[{TermType:'Semester 1'},{TermType:'Semester 2'}],UnitRequisiteRelationship_UnitRequisiteRelationship_UnitIDToUnit:[]});
 const plan=(id,name,units)=>({id,name,units,plannerTemplate:{requirements:[{unitType:{Name:'Major'},requiredCount:units.filter(u=>u.unitType.Name==='Major').length}]}});
 const primary=plan(1,'24-Sep-CSAI',[u('AAA10001'),u('COR10001','Core'),u('DSA10001','Elective')]);
 const old=plan(2,'23-Sep-CSDS',[u('DSA10001'),u('DSA10002')]);
 const same=plan(3,'24-Sep-CSDS',[u('DSA10001'),u('DSA10003')]);
 const feb=plan(4,'24-Feb-CSDS',[u('DSA10001'),u('DSA10002')]);
 const unknown=plan(5,'Data Science',[u('DSA10001'),u('DSA10002')]);
 const revision={...same,id:6,name:'24-Sep-CSDSr2'};
 const febPrimary={...primary,id:7,name:'23-Feb-CSAI'};
 const febSecond={...same,id:8,name:'23-Feb-CSDS'};
 const planners=[primary,old,feb,unknown,same,revision,febPrimary,febSecond];
 const transcript=parseTranscript([['Course','Status','Earned','Grade'],...['AAA10001','COR10001','DSA10001','DSA10002'].map(code=>[code,'Complete',12.5,'HD'])]);
 const original=JSON.stringify(transcript);
 const draft=doubleMajorPathway({transcript,planners});
 assert.equal(draft.primary.id,1);
 assert.equal(draft.secondary.id,3,'More completed units in another intake must not win');
 assert.equal(draft.intake.label,'24-Sep');
 assert.deepEqual(rankedSecondMajors(transcript,planners,primary).map(r=>r.planner.id),[3],'Filter intake before deduplicating major versions');
 assert.equal(draft.coverage.majors[1].matched,1);
 assert.equal(draft.coverage.majors[1].remaining,1);
 assert.deepEqual(draft.semesters.flatMap(s=>s.selected).map(u=>u.code),['DSA10003']);
 const febDraft=doubleMajorPathway({transcript,planners,primaryId:7});
 assert.equal(febDraft.secondary.id,8);assert.equal(febDraft.intake.label,'23-Feb');
 const revised=doubleMajorPathway({transcript,planners,primaryId:1,secondaryId:6});
 assert.equal(revised.secondary.id,6,'Revision suffixes do not change intake');
 for(const secondaryId of [2,4,5])assert.throws(()=>doubleMajorPathway({transcript,planners,primaryId:1,secondaryId}),/same intake/);
 assert.throws(()=>doubleMajorPathway({transcript,planners:[primary,old]}),/No different-major.*24-Sep/,'Never silently fall back to a different year');
 assert.throws(()=>doubleMajorPathway({transcript,planners:[{...primary,name:'AI'},same]}),/intake.*cannot be identified/);
 const choices=compatibleSecondMajorChoices(draft.choices,1);
 assert.deepEqual(choices.map(p=>p.id),[3,6]);
 assert.deepEqual(compatibleSecondMajorChoices(draft.choices,7).map(p=>p.id),[8]);
 assert.deepEqual(compatibleSecondMajorChoices(draft.choices,999),[]);
 assert.equal(draft.choices.some(p=>p.id===5),false,'Unknown intakes are not selectable');
 const legacy=assessDpaDoubleMajor(transcript,[primary,old,feb,same],1);
 assert.deepEqual(legacy.options.map(p=>p.additional.id),[3],'Legacy automatic suggestions must also stay within intake');
 assert.equal(JSON.stringify(transcript),original,'Matching never changes earned records');
 console.log('Same-intake double-major checks passed: year/month cohorts, S1/S2, stronger cross-intake matches, revisions, overrides, dropdown choices, missing partners and unchanged DPA.');
})().catch(e=>{console.error(e);process.exitCode=1;});
